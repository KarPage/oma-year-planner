#!/usr/bin/env python3
"""Write theme.css from the active Omarchy theme.

Reads ~/.local/state/omarchy/current/theme/colors.toml and emits CSS
variables the year planner uses. Re-run after a theme change, or use ./open
which does this before launching the window.
"""

from __future__ import annotations

import re
import tomllib
from pathlib import Path

THEME_DIR = Path.home() / ".local/state/omarchy/current/theme"
COLORS = THEME_DIR / "colors.toml"
NAME = THEME_DIR.parent / "theme.name"
OUT = Path(__file__).with_name("theme.css")

# Page tokens, in order. Each falls through toml keys until one exists.
ALIASES = {
    "bg": ("background", "bg"),
    "bg-raised": ("lighter_bg", "selection_background"),
    "bg-deep": ("dark_bg", "darker_bg", "background"),
    "fg": ("foreground", "fg"),
    "fg-dim": ("dark_fg", "light_fg", "foreground"),
    "muted": ("muted", "color8"),
    "accent": ("accent", "selection", "green"),
    "travel": ("green", "bright_green", "accent"),
    "work": ("blue", "bright_blue", "cyan"),
    "personal": ("yellow", "bright_yellow", "orange"),
    "other": ("cyan", "bright_cyan", "magenta"),
}


def parse_colors(text: str) -> tuple[str, dict[str, str]]:
    data = tomllib.loads(text)
    mode = data.get("mode", "dark")
    if not isinstance(mode, str):
        mode = "dark"
    colors: dict[str, str] = {}

    def walk(node: object) -> None:
        if not isinstance(node, dict):
            return
        for key, value in node.items():
            if isinstance(value, dict):
                walk(value)
            elif isinstance(value, str) and re.fullmatch(r"#[0-9a-fA-F]{6}", value):
                colors[str(key)] = value.lower()

    walk(data)
    return mode, colors


def pick(colors: dict[str, str], keys: tuple[str, ...], fallback: str) -> str:
    for key in keys:
        if key in colors:
            return colors[key]
    return fallback


def main() -> None:
    mode, colors = parse_colors(COLORS.read_text())
    theme_name = NAME.read_text().strip() if NAME.exists() else "current"
    # Fallbacks are the Osaka Jade values this page was first built against.
    fallbacks = {
        "bg": "#000d04",
        "bg-raised": "#171f1a",
        "bg-deep": "#000300",
        "fg": "#fcfff4",
        "fg-dim": "#d1d4ca",
        "muted": "#545754",
        "accent": "#41a468",
        "travel": "#74a869",
        "work": "#37a388",
        "personal": "#c0d1a4",
        "other": "#54bda1",
    }
    lines = [
        "/* Generated by apply-theme.py from the active Omarchy theme.",
        "   Do not edit. Run ./open or python3 apply-theme.py to refresh. */",
        f"/* theme: {theme_name} */",
        ":root {",
        f"  color-scheme: {mode if mode in {'dark', 'light'} else 'dark'};",
    ]
    for name, keys in ALIASES.items():
        lines.append(f"  --{name}: {pick(colors, keys, fallbacks[name])};")
    lines.append("}")
    lines.append("")
    OUT.write_text("\n".join(lines))
    print(f"{OUT}  ({theme_name}, {mode})")


if __name__ == "__main__":
    main()
